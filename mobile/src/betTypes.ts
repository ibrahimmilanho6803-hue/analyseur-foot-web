// Libellés d'anciennes versions : l'historique déjà enregistré continue de compter.
const LEGACY_LABELS: Record<string, string> = { "Total buts 1.5 plus": "Plus de 1.5 buts", "Victoire exterieur": "Victoire extérieur" };
export const canonicalLabel = (label: string): string => LEGACY_LABELS[label] || label;

/** Vrai pour un pari à ligne entière : la mise est remboursée quand le nombre de buts tombe exactement sur la ligne. */
export const isRefundable = (label: string): boolean => Object.prototype.hasOwnProperty.call(BASELINE_REFUND, canonicalLabel(label));

const goalsWord = (n: number): string => `${n} ${n > 1 ? "buts" : "but"}`;

/** Règle de remboursement d'un pari à ligne entière, en une phrase (le serveur donne ensuite la sienne, avec les noms des équipes). */
export function refundRuleText(label: string): string | null {
  const match = /^(?:Plus|Moins) de (\d+) buts?$/.exec(label);
  if (match) return `Si le match se termine avec exactement ${goalsWord(Number(match[1]))}, la mise est remboursée (ni gagnée, ni perdue).`;
  const team = /^Equipe (domicile|extérieur) (?:plus|moins) de (\d+) buts?$/.exec(label);
  if (team) return `Si l'équipe ${team[1] === "domicile" ? "1 (à domicile)" : "2 (à l'extérieur)"} marque exactement ${goalsWord(Number(team[2]))}, la mise est remboursée (ni gagnée, ni perdue).`;
  return null;
}
